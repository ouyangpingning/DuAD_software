def fill(src_ts, out_ts, mapping):
    tree = ET.parse(src_ts)
    root = tree.getroot()
    filled = 0
    for msg in root.iter("message"):
        source = msg.find("source")
        trans = msg.find("translation")
        if source is None or trans is None:
            continue
        key = source.text or ""
        if key in mapping:
            trans.text = mapping[key]
            if "type" in trans.attrib:
                del trans.attrib["type"]
            filled += 1
    tree.write(out_ts, encoding="utf-8", xml_declaration=True)
    print(f"{out_ts}: {filled} translations filled")


